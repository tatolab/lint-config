import subprocess
import sys
import tempfile
import textwrap
import unittest
from pathlib import Path

LINT_CONFIG = Path(__file__).resolve().parent.parent


def run(script: str, repository: Path, *arguments: str) -> subprocess.CompletedProcess[str]:
    """Runs one of lint-config's scripts in `repository`."""
    return subprocess.run([sys.executable, str(LINT_CONFIG / script), *arguments], cwd=repository, capture_output=True, text=True)


class RepositoryTestCase(unittest.TestCase):
    """A test with a scratch git repository whose files it writes and commits."""

    def setUp(self) -> None:
        self.directory = tempfile.TemporaryDirectory()
        self.repository = Path(self.directory.name)
        self.git("init", "-q", "-b", "main")

    def tearDown(self) -> None:
        self.directory.cleanup()

    def git(self, *arguments: str) -> None:
        subprocess.run(["git", "-c", "user.name=test", "-c", "user.email=test@example.invalid", *arguments], cwd=self.repository, check=True, capture_output=True)

    def write(self, path: str, text: str) -> None:
        file = self.repository / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(text)
        self.git("add", path)


class FileSizeTests(RepositoryTestCase):
    def check(self, *arguments: str) -> subprocess.CompletedProcess[str]:
        return run("file-size/check_file_sizes.py", self.repository, "--exceptions", "file-size-exceptions.txt", "--limit", "10", *arguments)

    def test_a_file_within_the_limit_passes(self) -> None:
        self.write("src/short.rs", "fn a() {}\n" * 10)
        self.assertEqual(self.check().returncode, 0)

    def test_a_file_over_the_limit_fails_unless_listed(self) -> None:
        self.write("src/long.rs", "fn a() {}\n" * 11)
        self.assertIn("src/long.rs: 11 lines, over 10", self.check().stderr)
        self.write("file-size-exceptions.txt", "11 src/long.rs\n")
        self.assertEqual(self.check().returncode, 0)

    def test_a_listed_file_may_not_grow(self) -> None:
        self.write("src/long.rs", "fn a() {}\n" * 12)
        self.write("file-size-exceptions.txt", "11 src/long.rs\n")
        self.assertIn("grown past its exception of 11", self.check().stderr)

    def test_an_entry_whose_file_is_back_under_the_limit_must_go(self) -> None:
        self.write("src/split.rs", "fn a() {}\n" * 3)
        self.write("file-size-exceptions.txt", "40 src/split.rs\n")
        self.assertIn("within the limit; remove the entry", self.check().stderr)

    def test_the_list_only_shrinks_against_the_ref(self) -> None:
        self.write("src/long.rs", "fn a() {}\n" * 12)
        self.write("file-size-exceptions.txt", "11 src/long.rs\n")
        self.git("commit", "-q", "-m", "base")
        self.write("file-size-exceptions.txt", "12 src/long.rs\n")
        self.assertIn("rose from 11 to 12", self.check("--compare-to", "main").stderr)
        self.write("src/other.rs", "fn a() {}\n" * 11)
        self.write("file-size-exceptions.txt", "12 src/long.rs\n11 src/other.rs\n")
        self.assertIn("src/other.rs is a new exception", self.check("--compare-to", "main").stderr)

    def test_generated_vendored_and_excluded_files_are_not_checked(self) -> None:
        self.write("src/generated.rs", "// @generated by a tool\n" + "fn a() {}\n" * 20)
        self.write("vendor/upstream/big.rs", "fn a() {}\n" * 20)
        self.write("ports/big.rs", "fn a() {}\n" * 20)
        self.assertEqual(self.check("--exclude", "ports/**").returncode, 0)

    def test_tighten_lowers_each_count_to_the_file_now(self) -> None:
        self.write("src/long.rs", "fn a() {}\n" * 12)
        self.write("file-size-exceptions.txt", "30 src/long.rs\n")
        self.assertEqual(self.check("--tighten").returncode, 0)
        self.assertEqual((self.repository / "file-size-exceptions.txt").read_text(), "12 src/long.rs\n")


class ModuleFileTests(RepositoryTestCase):
    def test_a_module_with_children_is_mod_rs(self) -> None:
        self.write("src/lib.rs", "mod graph;\n")
        self.write("src/graph/mod.rs", "mod nodes;\n")
        self.write("src/graph/nodes.rs", "")
        self.assertEqual(run("rust/check_module_files.py", self.repository).returncode, 0)

    def test_foo_rs_beside_a_foo_directory_fails(self) -> None:
        self.write("src/graph.rs", "mod nodes;\n")
        self.write("src/graph/nodes.rs", "")
        self.assertIn("src/graph/mod.rs", run("rust/check_module_files.py", self.repository).stderr)


class LintTableTests(RepositoryTestCase):
    CLIPPY = textwrap.dedent("""\
        disallowed-macros = [
            { path = "std::println", reason = "tracing" },
            { path = "std::eprintln", reason = "tracing" },
            { path = "std::print", reason = "tracing" },
            { path = "std::eprint", reason = "tracing" },
            { path = "std::dbg", reason = "tracing" },
        ]
        """)

    def check(self) -> subprocess.CompletedProcess[str]:
        return run("rust/check_lint_table.py", self.repository)

    def test_a_table_as_strict_as_the_reference_passes(self) -> None:
        self.write("Cargo.toml", '[workspace.lints.clippy]\ndisallowed_macros = "forbid"\nunwrap_used = "deny"\n')
        self.write("clippy.toml", self.CLIPPY)
        self.assertEqual(self.check().returncode, 0, self.check().stderr)

    def test_a_looser_or_missing_lint_fails(self) -> None:
        self.write("clippy.toml", self.CLIPPY)
        self.write("Cargo.toml", '[workspace.lints.clippy]\ndisallowed_macros = "warn"\n')
        self.assertIn("looser than lint-config's 'deny'", self.check().stderr)
        self.write("Cargo.toml", "[workspace]\n")
        self.assertIn("disallowed_macros is missing", self.check().stderr)

    def test_a_dropped_disallowed_macro_fails(self) -> None:
        self.write("Cargo.toml", '[workspace.lints.clippy]\ndisallowed_macros = "deny"\n')
        self.write("clippy.toml", self.CLIPPY.replace('    { path = "std::dbg", reason = "tracing" },\n', ""))
        self.assertIn("lacks std::dbg", self.check().stderr)


if __name__ == "__main__":
    unittest.main()
